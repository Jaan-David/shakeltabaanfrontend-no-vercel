type ProductBadgeContext = {
  category?: string;
  withInstallation?: boolean;
  isOffer?: boolean;
};

export const buildProductBadgesByCategory = ({
  category,
  withInstallation,
  isOffer,
}: ProductBadgeContext): string[] => {
  const categoryId = resolveApprovedCategoryId(category);
  if (!categoryId) {
    const fallback = ["جودة موثوقة"];
    if (withInstallation) fallback.push("تركيب متاح");
    if (isOffer) fallback.push("عرض خاص");
    return fallback;
  }

  const baseBadges = [...categoryContentMap[categoryId].badgeLogic];
  if (withInstallation) baseBadges.push("تركيب متاح");
  if (isOffer) baseBadges.push("عرض خاص");
  return Array.from(new Set(baseBadges));
};